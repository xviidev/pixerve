use crate::{config::number, params::Transforms};
use anyhow::{Result, ensure};
use percent_encoding::{AsciiSet, CONTROLS, utf8_percent_encode};
use sha2::{Digest, Sha256};
use std::{collections::HashMap, env};

const PATH_ESCAPE: &AsciiSet = &CONTROLS
    .add(b' ')
    .add(b'"')
    .add(b'#')
    .add(b'%')
    .add(b'<')
    .add(b'>')
    .add(b'?')
    .add(b'`')
    .add(b'{')
    .add(b'}');

#[derive(Clone)]
pub struct Settings {
    pub pipeline: String,
    pub private: bool,
    pub browser_ttl: u64,
    pub edge_ttl: u64,
    pub immutable_ttl: u64,
    pub swr: u64,
    pub stale_error: u64,
    pub redirects: bool,
    pub presets_only: bool,
    pub metrics_token: String,
    pub origin_token: String,
}

impl Settings {
    pub fn load() -> Result<Self> {
        let visibility = env::var("CACHE_VISIBILITY").unwrap_or_else(|_| "public".into());
        ensure!(
            ["public", "private"].contains(&visibility.as_str()),
            "Invalid CACHE_VISIBILITY"
        );
        let c = Self {
            pipeline: env::var("PIPELINE_VERSION").unwrap_or_else(|_| "1".into()),
            private: visibility == "private",
            browser_ttl: number("BROWSER_CACHE_TTL", 300)?,
            edge_ttl: number("CDN_CACHE_TTL", 86400)?,
            immutable_ttl: number("IMMUTABLE_CACHE_TTL", 31536000)?,
            swr: number("STALE_WHILE_REVALIDATE", 60)?,
            stale_error: number("STALE_IF_ERROR", 86400)?,
            redirects: number("CANONICAL_REDIRECTS", true)?,
            presets_only: number("PRESETS_ONLY", false)?,
            metrics_token: env::var("METRICS_TOKEN").unwrap_or_default(),
            origin_token: env::var("ORIGIN_TOKEN").unwrap_or_default(),
        };
        ensure!(
            !c.pipeline.is_empty()
                && c.pipeline.len() <= 32
                && c.pipeline
                    .bytes()
                    .all(|v| v.is_ascii_alphanumeric() || b"-_.".contains(&v)),
            "Invalid PIPELINE_VERSION"
        );
        ensure!(
            [
                c.browser_ttl,
                c.edge_ttl,
                c.immutable_ttl,
                c.swr,
                c.stale_error
            ]
            .iter()
            .all(|v| *v <= 31536000),
            "Cache durations must be at most one year"
        );
        ensure!(
            c.metrics_token.is_empty() || c.metrics_token.len() >= 16,
            "METRICS_TOKEN must contain at least 16 characters"
        );
        ensure!(
            c.origin_token.is_empty() || c.origin_token.len() >= 16,
            "ORIGIN_TOKEN must contain at least 16 characters"
        );
        Ok(c)
    }

    pub fn cache_control(&self, immutable: bool, remaining: u64) -> String {
        if self.private {
            return "private, no-store".into();
        }
        if immutable {
            return format!(
                "public, max-age={}, s-maxage={}, immutable",
                self.immutable_ttl, self.immutable_ttl
            );
        }
        // Do not renew the CDN freshness of an old mutable origin cache entry.
        let edge = self.edge_ttl.min(remaining);
        let browser = self.browser_ttl.min(edge);
        format!(
            "public, max-age={browser}, s-maxage={edge}, stale-while-revalidate={}, stale-if-error={}",
            self.swr, self.stale_error
        )
    }
}

/// Immutable names are generated by `pixerve version`: <stem>-<full sha256>.<ext>.
pub fn source_hash(path: &str) -> Option<&str> {
    let name = path.rsplit('/').next()?;
    let stem = name.rsplit_once('.').map_or(name, |(stem, _)| stem);
    let (_, hash) = stem.rsplit_once('-')?;
    (hash.len() == 64
        && hash
            .bytes()
            .all(|c| c.is_ascii_digit() || (b'a'..=b'f').contains(&c)))
    .then_some(hash)
}

pub fn verify_source(path: &str, bytes: &[u8]) -> bool {
    source_hash(path).is_none_or(|hash| hex::encode(Sha256::digest(bytes)) == hash)
}

pub fn canonical_url(
    file: &str,
    t: &Transforms,
    og: bool,
    static_file: bool,
    pipeline: Option<&str>,
    auth: &HashMap<String, String>,
) -> String {
    let file = utf8_percent_encode(file, PATH_ESCAPE);
    let norm = t.normalize();
    let mut url = if og {
        format!("/og/{file}")
    } else if static_file {
        format!("/static/{file}")
    } else if norm.is_empty() {
        format!("/{file}")
    } else {
        format!(
            "/tr:{}/{file}",
            norm.split(',')
                .filter(|p| p.starts_with("f="))
                .chain(norm.split(',').filter(|p| !p.starts_with("f=")))
                .map(|pair| pair.replacen('=', "-", 1))
                .collect::<Vec<_>>()
                .join(",")
        )
    };
    let mut query: Vec<(&str, &str)> = Vec::new();
    if let Some(pv) = pipeline {
        query.push(("pv", pv));
    }
    if let Some(sig) = auth.get("asig") {
        query.push(("asig", sig));
    }
    if let Some(sig) = auth.get("sig").or_else(|| auth.get("s")) {
        query.push(("sig", sig));
    }
    if let Some(exp) = auth.get("exp").or_else(|| auth.get("e")) {
        query.push(("exp", exp));
    }
    if !query.is_empty() {
        url.push('?');
        url.push_str(&serde_urlencoded::to_string(query).expect("String params are serializable"));
    }
    url
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn cache_policy_does_not_renew_old_entries_or_cache_private_images() {
        let mut s = Settings {
            pipeline: "1".into(),
            private: false,
            browser_ttl: 300,
            edge_ttl: 86400,
            immutable_ttl: 31536000,
            swr: 60,
            stale_error: 86400,
            redirects: true,
            presets_only: false,
            metrics_token: String::new(),
            origin_token: String::new(),
        };
        assert_eq!(
            s.cache_control(false, 5),
            "public, max-age=5, s-maxage=5, stale-while-revalidate=60, stale-if-error=86400"
        );
        assert!(!s.cache_control(false, 86400).contains("immutable"));
        assert!(s.cache_control(true, 5).contains("max-age=31536000"));
        s.private = true;
        assert_eq!(s.cache_control(true, 31536000), "private, no-store");
    }
    #[test]
    fn fingerprints_are_verified_and_canonical_paths_are_safe() {
        let digest = hex::encode(Sha256::digest(b"photo"));
        let file = format!("news/photo-{digest}.jpg");
        assert!(verify_source(&file, b"photo"));
        assert!(!verify_source(&file, b"replaced"));
        assert!(source_hash("photo-a81f2c.jpg").is_none());
        let t = Transforms::parse(&HashMap::from([("p".into(), "card".into())])).unwrap();
        let url = canonical_url(
            "news/a ?%.jpg",
            &t,
            false,
            false,
            Some("2"),
            &HashMap::new(),
        );
        assert!(url.starts_with("/tr:f-webp,w-640,h-360,q-75,fit-cover/"));
        assert!(url.ends_with("a%20%3F%25.jpg?pv=2"));
    }
}
